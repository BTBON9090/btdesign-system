import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import ts from 'typescript';
import postcss from 'postcss';

// The Studio renderers are canonical. Ship their source as static strings for browser exports.
const location = (path) => fileURLToPath(new URL(path, import.meta.url));
const source = readFileSync(location('../../../apps/docs/src/studio/ScenePreview.tsx'), 'utf8');
const stylesheet = readFileSync(location('../../../apps/docs/src/studio/ScenePreview.css'), 'utf8');
const file = ts.createSourceFile(
  'ScenePreview.tsx',
  source,
  ts.ScriptTarget.Latest,
  true,
  ts.ScriptKind.TSX,
);
const top = (name) => {
  const statement = file.statements.find(
    (node) =>
      node.name?.getText(file) === name ||
      (ts.isVariableStatement(node) &&
        node.declarationList.declarations.some((d) => d.name.getText(file) === name)),
  );
  if (!statement) throw new Error(`Missing canonical scene definition: ${name}`);
  return statement.getText(file);
};
const common = ['SceneSelection', 'seedMembers', 'ProjectCard', 'initialCards']
  .map(top)
  .join('\n\n');
const react = ['Mark', 'SceneTop', 'ReactScene'].map(top).join('\n\n');
const vueFunction = file.statements.find(
  (node) => ts.isFunctionDeclaration(node) && node.name.text === 'VueScene',
);
if (!vueFunction) throw new Error('Missing Vue renderer');
let renderer;
const helpers = new Map();
function walk(node) {
  if (ts.isCallExpression(node) && node.expression.getText(file) === 'defineComponent')
    renderer = node;
  if (ts.isVariableStatement(node))
    for (const declaration of node.declarationList.declarations) {
      const name = declaration.name.getText(file);
      if (['mark', 'field', 'icon', 'symbol'].includes(name)) helpers.set(name, node.getText(file));
    }
  ts.forEachChild(node, walk);
}
walk(vueFunction);
if (!renderer || helpers.size !== 4)
  throw new Error('Incomplete canonical Vue renderer extraction');
const vue =
  [...helpers.values()].join('\n\n') + '\n\nconst Scene = ' + renderer.getText(file) + ';';
const css = postcss.parse(stylesheet);
css.walkRules((rule) => {
  if (rule.selectors.some((selector) => selector.includes('.sp-inspecting'))) {
    rule.remove();
    return;
  }
  rule.selectors = rule.selectors.map((selector) =>
    selector.includes('.sp-scene')
      ? selector.replaceAll('.sp-scene', '.btdesign-demo.sp-scene')
      : '.btdesign-demo ' + selector,
  );
});
const styles =
  css.toString() +
  `\n.btdesign-demo .sr-only { position: absolute; width: 1px; height: 1px; padding: 0; overflow: hidden; clip: rect(0, 0, 0, 0); white-space: nowrap; }\n.btdesign-demo-controls { display:flex; align-items:center; justify-content:space-between; gap:16px; padding:14px 24px; border-top:1px solid var(--f-border); color:var(--f-muted); font:12px/1.6 var(--f-font); }\n.btdesign-demo-controls p { margin:0; }\n`;
const values = {
  commonSceneSource: common,
  reactSceneSource: react,
  vueSceneSource: vue,
  sceneCss: styles,
  sceneSourceFingerprint: createHash('sha256').update(source).update(stylesheet).digest('hex'),
};
writeFileSync(
  location('../src/scenes.generated.ts'),
  '// Generated by scripts/sync-scenes.mjs from the canonical Studio renderers.\n' +
    Object.entries(values)
      .map(([name, value]) => `export const ${name} = ${JSON.stringify(value)};`)
      .join('\n') +
    '\n',
);
